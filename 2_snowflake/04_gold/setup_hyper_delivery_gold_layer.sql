
-- =========================================
-- GOLD: ORDER STATUS SUMMARY
-- =========================================

CREATE OR REPLACE TABLE
HYPER_DELIVERY_DB.GOLD.GOLD_ORDERS_STATUS AS

WITH LATEST_ORDERS AS
(
    SELECT
        ORDER_ID,
        ORDER_STATUS,
        INGESTION_TIME

    FROM HYPER_DELIVERY_DB.SILVER.SILVER_ORDER_EVENTS

    QUALIFY ROW_NUMBER() OVER
    (
        PARTITION BY ORDER_ID
        ORDER BY INGESTION_TIME DESC,
                 SOURCE_FILE DESC,
                 FILE_ROW_NUMBER DESC
    ) = 1
)

SELECT
    ORDER_STATUS,
    COUNT(*) AS ORDER_COUNT

FROM LATEST_ORDERS

GROUP BY ORDER_STATUS;

-- =========================================
-- GOLD: PRODUCT POPULARITY
-- =========================================

CREATE OR REPLACE TABLE
HYPER_DELIVERY_DB.GOLD.GOLD_PRODUCT_POPULARITY AS

SELECT
    PRODUCT_NAME,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS

FROM HYPER_DELIVERY_DB.SILVER.SILVER_PRODUCT_EVENTS

GROUP BY PRODUCT_NAME

ORDER BY TOTAL_ORDERS DESC;

-- =========================================
-- GOLD: RIDER STATUS
-- =========================================

CREATE OR REPLACE TABLE
HYPER_DELIVERY_DB.GOLD.GOLD_RIDER_STATUS AS

WITH LATEST_RIDERS AS
(
    SELECT
        RIDER_ID,
        CITY,
        RIDER_STATUS,
        CURRENT_ORDERS,
        INGESTION_TIME

    FROM HYPER_DELIVERY_DB.SILVER.SILVER_RIDER_EVENTS

    QUALIFY ROW_NUMBER() OVER
    (
        PARTITION BY RIDER_ID
        ORDER BY INGESTION_TIME DESC,
                 SOURCE_FILE DESC,
                 FILE_ROW_NUMBER DESC
    ) = 1
)

SELECT
    RIDER_STATUS,
    COUNT(*) AS RIDER_COUNT

FROM LATEST_RIDERS

GROUP BY RIDER_STATUS;


-- =========================================
-- GOLD: BUSINESS METRICS
-- =========================================

CREATE OR REPLACE TABLE
HYPER_DELIVERY_DB.GOLD.GOLD_BUSINESS_METRICS AS

WITH PARSED_DELIVERIES AS
(
    SELECT
        DELIVERY_ID,
        CITY,
        DELIVERY_STATUS,
        EXPECTED_DELIVERY_MINUTES,
        ACTUAL_DELIVERY_MINUTES,

        TRY_TO_TIMESTAMP_TZ(EVENT_TIME) AS EVENT_TS,

        INGESTION_TIME,
        SOURCE_FILE,
        FILE_ROW_NUMBER

    FROM HYPER_DELIVERY_DB.SILVER.SILVER_DELIVERY_EVENTS

    WHERE DELIVERY_ID IS NOT NULL
),

LATEST_DELIVERIES AS
(
    SELECT *

    FROM PARSED_DELIVERIES

    WHERE EVENT_TS IS NOT NULL

    QUALIFY ROW_NUMBER() OVER
    (
        PARTITION BY DELIVERY_ID
        ORDER BY EVENT_TS DESC,
                 INGESTION_TIME DESC,
                 SOURCE_FILE DESC,
                 FILE_ROW_NUMBER DESC
    ) = 1
),

WINDOWED_DELIVERIES AS
(
    SELECT
        CITY,

        DATEADD(
            'hour',
            FLOOR(DATE_PART('hour', EVENT_TS) / 3) * 3,
            DATE_TRUNC('day', EVENT_TS)
        ) AS WINDOW_START,

        DELIVERY_STATUS,
        EXPECTED_DELIVERY_MINUTES,
        ACTUAL_DELIVERY_MINUTES

    FROM LATEST_DELIVERIES
)

SELECT
    CITY,
    WINDOW_START,

    DATEADD('hour', 3, WINDOW_START) AS WINDOW_END,

    COUNT(*) AS TOTAL_DELIVERIES,

    SUM(IFF(DELIVERY_STATUS = 'ON_TIME', 1, 0))
        AS ON_TIME_DELIVERIES,

    SUM(IFF(DELIVERY_STATUS = 'DELAYED', 1, 0))
        AS DELAYED_DELIVERIES,

    ROUND(
        100.0 * SUM(IFF(DELIVERY_STATUS = 'ON_TIME', 1, 0))
        / NULLIF(COUNT(*), 0),
        2
    ) AS ON_TIME_RATE_PCT,

    ROUND(AVG(ACTUAL_DELIVERY_MINUTES), 2)
        AS AVG_ACTUAL_DELIVERY_MINUTES,

    ROUND(AVG(EXPECTED_DELIVERY_MINUTES), 2)
        AS AVG_EXPECTED_DELIVERY_MINUTES

FROM WINDOWED_DELIVERIES

GROUP BY CITY, WINDOW_START;
