
-- ============================================================
-- HYPER DELIVERY DATA ENGINEERING
-- BRONZE LAYER SETUP
-- Source: AWS S3
-- Format: JSON
-- Destination: Snowflake BRONZE schema
-- ============================================================


-- 1. DATABASE AND SCHEMA

USE DATABASE HYPER_DELIVERY_DB;

CREATE SCHEMA IF NOT EXISTS BRONZE;


-- 2. JSON FILE FORMAT
-- Reuses the existing file format if already created.

CREATE FILE FORMAT IF NOT EXISTS
    HYPER_DELIVERY_DB.BRONZE.JSON_FORMAT
    TYPE = JSON;


-- 3. BRONZE ORDER EVENTS TABLE

CREATE TABLE IF NOT EXISTS
    HYPER_DELIVERY_DB.BRONZE.BRONZE_ORDER_EVENTS
(
    EVENT VARIANT,

    SOURCE_FILE VARCHAR,
    FILE_ROW_NUMBER NUMBER,
    FILE_CONTENT_KEY VARCHAR,

    FILE_LAST_MODIFIED TIMESTAMP_NTZ,
    LOAD_SCAN_TIME TIMESTAMP_LTZ
);


-- 4. BRONZE DELIVERY EVENTS TABLE

CREATE TABLE IF NOT EXISTS
    HYPER_DELIVERY_DB.BRONZE.BRONZE_DELIVERY_EVENTS
(
    EVENT VARIANT,

    SOURCE_FILE VARCHAR,
    FILE_ROW_NUMBER NUMBER,
    FILE_CONTENT_KEY VARCHAR,

    FILE_LAST_MODIFIED TIMESTAMP_NTZ,
    LOAD_SCAN_TIME TIMESTAMP_LTZ
);


-- 5. BRONZE PRODUCT EVENTS TABLE

CREATE TABLE IF NOT EXISTS
    HYPER_DELIVERY_DB.BRONZE.BRONZE_PRODUCT_EVENTS
(
    EVENT VARIANT,

    SOURCE_FILE VARCHAR,
    FILE_ROW_NUMBER NUMBER,
    FILE_CONTENT_KEY VARCHAR,

    FILE_LAST_MODIFIED TIMESTAMP_NTZ,
    LOAD_SCAN_TIME TIMESTAMP_LTZ
);


-- 6. BRONZE RIDER EVENTS TABLE

CREATE TABLE IF NOT EXISTS
    HYPER_DELIVERY_DB.BRONZE.BRONZE_RIDER_EVENTS
(
    EVENT VARIANT,

    SOURCE_FILE VARCHAR,
    FILE_ROW_NUMBER NUMBER,
    FILE_CONTENT_KEY VARCHAR,

    FILE_LAST_MODIFIED TIMESTAMP_NTZ,
    LOAD_SCAN_TIME TIMESTAMP_LTZ
);


-- ============================================================
-- 7. LOAD DATA FROM AWS S3 INTO BRONZE
-- Existing external stage: S3_RAW_STAGE
-- Existing file format: JSON_FORMAT
-- ============================================================


-- ORDERS

COPY INTO HYPER_DELIVERY_DB.BRONZE.BRONZE_ORDER_EVENTS
(
    EVENT,
    SOURCE_FILE,
    FILE_ROW_NUMBER,
    FILE_CONTENT_KEY,
    FILE_LAST_MODIFIED,
    LOAD_SCAN_TIME
)
FROM
(
    SELECT
        $1,
        METADATA$FILENAME,
        METADATA$FILE_ROW_NUMBER,
        METADATA$FILE_CONTENT_KEY,
        METADATA$FILE_LAST_MODIFIED,
        METADATA$START_SCAN_TIME

    FROM @HYPER_DELIVERY_DB.BRONZE.S3_RAW_STAGE/quick_commerce_order_events/
    (FILE_FORMAT => 'HYPER_DELIVERY_DB.BRONZE.JSON_FORMAT')
)
ON_ERROR = 'ABORT_STATEMENT';


-- DELIVERIES

COPY INTO HYPER_DELIVERY_DB.BRONZE.BRONZE_DELIVERY_EVENTS
(
    EVENT,
    SOURCE_FILE,
    FILE_ROW_NUMBER,
    FILE_CONTENT_KEY,
    FILE_LAST_MODIFIED,
    LOAD_SCAN_TIME
)
FROM
(
    SELECT
        $1,
        METADATA$FILENAME,
        METADATA$FILE_ROW_NUMBER,
        METADATA$FILE_CONTENT_KEY,
        METADATA$FILE_LAST_MODIFIED,
        METADATA$START_SCAN_TIME

    FROM @HYPER_DELIVERY_DB.BRONZE.S3_RAW_STAGE/quick_commerce_delivery_events/
    (FILE_FORMAT => 'HYPER_DELIVERY_DB.BRONZE.JSON_FORMAT')
)
ON_ERROR = 'ABORT_STATEMENT';


