INSERT INTO HYPER_DELIVERY_DB.SILVER.SILVER_PRODUCT_EVENTS
(
    PRODUCT_ID,
    PRODUCT_NAME,
    CATEGORY,
    ORDER_ID,
    STORE_ID,
    CITY,
    QUANTITY,
    PRICE,
    EVENT_TIME,
    SOURCE_FILE,
    FILE_ROW_NUMBER,
    FILE_CONTENT_KEY,
    FILE_LAST_MODIFIED,
    LOAD_SCAN_TIME,
    INGESTION_TIME
)

SELECT
    b.EVENT:product_id::VARCHAR,
    b.EVENT:product_name::VARCHAR,
    b.EVENT:category::VARCHAR,
    b.EVENT:order_id::VARCHAR,
    b.EVENT:store_id::VARCHAR,
    b.EVENT:city::VARCHAR,

    TRY_TO_NUMBER(b.EVENT:quantity::VARCHAR),
    TRY_TO_DOUBLE(b.EVENT:price::VARCHAR),

    b.EVENT:event_time::VARCHAR,

    b.SOURCE_FILE,
    b.FILE_ROW_NUMBER,
    b.FILE_CONTENT_KEY,
    b.FILE_LAST_MODIFIED,
    b.LOAD_SCAN_TIME,

    CURRENT_TIMESTAMP()

FROM HYPER_DELIVERY_DB.BRONZE.BRONZE_PRODUCT_EVENTS b

WHERE b.EVENT:product_id IS NOT NULL

AND NOT EXISTS
(
    SELECT 1
    FROM HYPER_DELIVERY_DB.SILVER.SILVER_PRODUCT_EVENTS s
    WHERE s.SOURCE_FILE = b.SOURCE_FILE
      AND s.FILE_ROW_NUMBER = b.FILE_ROW_NUMBER
);

