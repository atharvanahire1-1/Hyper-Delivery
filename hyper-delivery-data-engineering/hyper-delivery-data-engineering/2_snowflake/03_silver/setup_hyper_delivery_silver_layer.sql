
-- =========================================
-- SILVER LAYER: ORDER EVENTS
-- =========================================

CREATE TABLE IF NOT EXISTS
HYPER_DELIVERY_DB.SILVER.SILVER_ORDER_EVENTS
(
    ORDER_ID VARCHAR,
    USER_ID VARCHAR,
    STORE_ID VARCHAR,
    CITY VARCHAR,
    ORDER_STATUS VARCHAR,
    ORDER_VALUE FLOAT,
    ITEMS_COUNT NUMBER(10,0),
    ORDER_TIME VARCHAR,
    EVENT_TIME VARCHAR,

    -- S3 metadata for data lineage
    SOURCE_FILE VARCHAR,
    FILE_ROW_NUMBER NUMBER,
    FILE_CONTENT_KEY VARCHAR,
    FILE_LAST_MODIFIED TIMESTAMP_NTZ,
    LOAD_SCAN_TIME TIMESTAMP_LTZ,

    -- When Silver processing happened
    INGESTION_TIME TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

