-- =========================================
-- INSERT DELIVERY EVENTS INTO SILVER
-- =========================================

INSERT INTO HYPER_DELIVERY_DB.SILVER.SILVER_DELIVERY_EVENTS
(
    DELIVERY_ID,
    ORDER_ID,
    RIDER_ID,
    STORE_ID,
    CITY,
    EXPECTED_DELIVERY_MINUTES,
    ACTUAL_DELIVERY_MINUTES,
    DELIVERY_STATUS,
    DELIVERY_TIME,
    EVENT_TIME,
    SOURCE_FILE,
    FILE_ROW_NUMBER,
    FILE_CONTENT_KEY,
    FILE_LAST_MODIFIED,
    LOAD_SCAN_TIME,
    INGESTION_TIME
)

SELECT
    b.EVENT:delivery_id::VARCHAR,
    b.EVENT:order_id::VARCHAR,
    b.EVENT:rider_id::VARCHAR,
    b.EVENT:store_id::VARCHAR,
    b.EVENT:city::VARCHAR,

    TRY_TO_NUMBER(b.EVENT:expected_delivery_minutes::VARCHAR),
    TRY_TO_NUMBER(b.EVENT:actual_delivery_minutes::VARCHAR),

    b.EVENT:delivery_status::VARCHAR,
    b.EVENT:delivery_time::VARCHAR,
    b.EVENT:event_time::VARCHAR,

    b.SOURCE_FILE,
    b.FILE_ROW_NUMBER,
    b.FILE_CONTENT_KEY,
    b.FILE_LAST_MODIFIED,
    b.LOAD_SCAN_TIME,

    CURRENT_TIMESTAMP()

FROM HYPER_DELIVERY_DB.BRONZE.BRONZE_DELIVERY_EVENTS b

WHERE b.EVENT:delivery_id IS NOT NULL

AND NOT EXISTS
(
    SELECT 1
    FROM HYPER_DELIVERY_DB.SILVER.SILVER_DELIVERY_EVENTS s
    WHERE s.DELIVERY_ID = b.EVENT:delivery_id::VARCHAR
);

